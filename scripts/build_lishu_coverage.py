#!/usr/bin/env python3
"""从教育部隶书原始 TTF 的 Unicode 映射生成页面覆盖表；不修改字体。"""
import json
import struct
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent


def font_chars(path):
    data = path.read_bytes()
    if data[:4] != b'\x00\x01\x00\x00':
        raise ValueError('需要 TrueType 字体文件')
    u16 = lambda b, o: struct.unpack_from('>H', b, o)[0]
    u32 = lambda b, o: struct.unpack_from('>I', b, o)[0]
    tables = {}
    for i in range(u16(data, 4)):
        pos = 12 + 16 * i
        tag, _, offset, length = struct.unpack_from('>4sIII', data, pos)
        if offset + length > len(data):
            raise ValueError(f'字体数据不完整：{tag!r}')
        tables[tag] = data[offset:offset + length]
    cmap, mapping = tables[b'cmap'], {}
    for i in range(u16(cmap, 2)):
        platform, encoding, start = struct.unpack_from('>HHI', cmap, 4 + 8 * i)
        if not (platform == 0 or platform == 3 and encoding in (1, 10)):
            continue
        fmt = u16(cmap, start)
        if fmt == 4:
            table = cmap[start:start + u16(cmap, start + 2)]
            segments = u16(table, 6) // 2
            for j in range(segments):
                end = u16(table, 14 + 2 * j)
                begin = u16(table, 16 + 2 * segments + 2 * j)
                delta = u16(table, 16 + 4 * segments + 2 * j)
                range_at = 16 + 6 * segments + 2 * j
                shift = u16(table, range_at)
                for cp in range(begin, min(end + 1, 0xFFFF)):
                    if shift:
                        glyph = u16(table, range_at + shift + 2 * (cp - begin))
                        glyph = (glyph + delta) & 0xFFFF if glyph else 0
                    else:
                        glyph = (cp + delta) & 0xFFFF
                    if glyph:
                        mapping[cp] = glyph
        elif fmt == 12:
            for j in range(u32(cmap, start + 12)):
                begin, end, first = struct.unpack_from('>III', cmap, start + 16 + 12 * j)
                if begin > end or end > 0x10FFFF:
                    raise ValueError('无效的 Unicode 字符映射')
                for cp in range(begin, end + 1):
                    if first + cp - begin:
                        mapping[cp] = first + cp - begin
    glyph_count = u16(tables[b'maxp'], 4)
    long_loca = u16(tables[b'head'], 50) == 1
    loca = tables[b'loca']
    glyph_offset = lambda g: u32(loca, g * 4) if long_loca else u16(loca, g * 2) * 2
    chars = set()
    for cp, glyph in mapping.items():
        if glyph >= glyph_count:
            raise ValueError('字形编号超出字体范围')
        if glyph_offset(glyph + 1) > glyph_offset(glyph):
            chars.add(chr(cp))
    if not chars:
        raise ValueError('字体没有可用的 Unicode 字形')
    return chars


def main():
    chars = font_chars(BASE / 'fonts' / 'moe-lishu.ttf')
    output = BASE / 'fonts' / 'lishu-coverage.js'
    output.write_text(
        '// Generated by scripts/build_lishu_coverage.py.\nconst LISHU_COVERAGE = '
        + json.dumps(''.join(sorted(chars)), ensure_ascii=False) + ';\n',
        encoding='utf-8',
    )
    print(f'{output.name}: {len(chars)} 个非空字形字符映射')


if __name__ == '__main__':
    main()
