#!/usr/bin/env python3
"""Build local WOFF2 lookup subsets from Jigmo's 2025-09-12 TTF release."""

import argparse
import json
import re
from pathlib import Path
from xml.etree import ElementTree

from fontTools import subset
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parent.parent
FONT_NAMES = ('Jigmo', 'Jigmo2', 'Jigmo3')
GLYPHS_PER_FILE = 2048
GLYPHWIKI_POINT = 0x2B81E


def unicode_points(css):
    for ranges in re.findall(r'unicode-range\s*:\s*([^;}]+)', css):
        for start, end in re.findall(r'U\+([0-9A-F]+)(?:-([0-9A-F]+))?', ranges, re.I):
            yield from range(int(start, 16), int(end or start, 16) + 1)


def song_coverage():
    directory = ROOT / 'fonts/web/song'
    css = (directory / 'font.css').read_text(encoding='utf-8')
    covered = set()
    for face in css.split('@font-face')[1:]:
        filename = re.search(r'url\(["\']?([^"\')]+)', face)[1]
        with TTFont(directory / filename) as font:
            mapped = {cp for table in font['cmap'].tables if table.isUnicode() and table.format != 14
                      for cp in table.cmap}
        covered.update(mapped.intersection(unicode_points(face)))
    return covered


def unicode_ranges(points):
    ranges = []
    for point in points:
        if ranges and ranges[-1][1] + 1 == point:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    return ','.join(f'U+{first:X}-{last:X}' if first != last else f'U+{first:X}'
                    for first, last in ranges)


def font_face(filename, points):
    return (f'@font-face {{\n  font-family: "Jigmo Lookup";\n'
            f'  src: url("{filename}") format("woff2");\n'
            f'  font-display: swap;\n  unicode-range: {unicode_ranges(points)};\n}}\n')


def build_glyphwiki_font(svg, output):
    document = ElementTree.parse(svg).getroot()
    paths = document.findall('.//{http://www.w3.org/2000/svg}path')
    if document.get('viewBox') != '0 0 200 200' or not paths:
        raise ValueError('Expected the GlyphWiki u2b81e-g.svg outline')
    pen = TTGlyphPen({})
    scaled = TransformPen(pen, (5, 0, 0, -5, 0, 880))
    for path in paths:
        parse_path(path.attrib['d'], scaled)

    name = 'uni2B81E'
    font = FontBuilder(1000, isTTF=True)
    font.setupGlyphOrder(['.notdef', name])
    font.setupCharacterMap({GLYPHWIKI_POINT: name})
    font.setupGlyf({'.notdef': TTGlyphPen({}).glyph(), name: pen.glyph()})
    font.setupHorizontalMetrics({'.notdef': (1000, 0), name: (1000, font.font['glyf'][name].xMin)})
    font.setupHorizontalHeader(ascent=880, descent=-120)
    font.setupNameTable({'familyName': 'GlyphWiki Reference', 'styleName': 'Regular',
                         'psName': 'GlyphWikiReference', 'uniqueFontIdentifier': 'GlyphWiki-U2B81E-G'})
    font.setupOS2(sTypoAscender=880, sTypoDescender=-120, usWinAscent=880, usWinDescent=120)
    font.setupPost()
    font.font.flavor = 'woff2'
    font.save(output)


def build(source, output, glyphwiki_svg):
    index = json.loads((ROOT / 'assets/variant-index.json').read_text(encoding='utf-8'))
    indexed = {ord(char) for char in index['chars']}
    remaining = indexed - song_coverage()
    styles = []
    options = subset.Options()
    options.flavor = 'woff2'
    options.hinting = False
    options.drop_tables += ['GSUB', 'GPOS', 'GDEF', 'vhea', 'vmtx', 'VORG', 'FFTM']
    output.mkdir(parents=True, exist_ok=True)
    for name in FONT_NAMES:
        source_font = source / f'{name}.ttf'
        with TTFont(source_font) as font:
            points = sorted(remaining.intersection(font.getBestCmap()))
        remaining.difference_update(points)
        for offset in range(0, len(points), GLYPHS_PER_FILE):
            chunk = points[offset:offset + GLYPHS_PER_FILE]
            filename = f'{chunk[0]:05x}-{chunk[-1]:05x}.woff2'
            with TTFont(source_font) as font:
                builder = subset.Subsetter(options=options)
                builder.populate(unicodes=chunk)
                builder.subset(font)
                font.flavor = 'woff2'
                font.save(output / filename)
            styles.append(font_face(filename, chunk))

    if GLYPHWIKI_POINT in remaining:
        filename = 'glyphwiki-2b81e.woff2'
        build_glyphwiki_font(glyphwiki_svg, output / filename)
        styles.append(font_face(filename, [GLYPHWIKI_POINT]))
        remaining.remove(GLYPHWIKI_POINT)

    (output / 'font.css').write_text(
        '/* Generated by scripts/build_lookup_fonts.py from Jigmo 2025-09-12 and GlyphWiki. */\n'
        + '\n'.join(styles), encoding='utf-8')
    print(f'{len(indexed):,} indexed characters, {len(styles)} font subsets, '
          f'{len(remaining)} without a bundled glyph')
    if remaining:
        print('Uncovered: ' + ', '.join(f'U+{cp:04X}' for cp in sorted(remaining)))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='directory containing Jigmo/Jigmo2/Jigmo3.ttf')
    parser.add_argument('output', type=Path, help='directory for WOFF2 and font.css')
    parser.add_argument('--glyphwiki-svg', required=True, type=Path, help='GlyphWiki u2b81e-g.svg')
    args = parser.parse_args()
    build(args.source, args.output, args.glyphwiki_svg)
