#!/usr/bin/env python3
"""生成现代规范部首的自身笔画，主字库优先，再补字典及 Unihan。"""
import argparse
import json
from pathlib import Path
import zipfile

BASE = Path(__file__).resolve().parent.parent
# Unicode 18.0 Equivalent_Unified_Ideograph 中的近同形偏旁，用于补充符号区笔画。
# https://www.unicode.org/Public/18.0.0/ucd/EquivalentUnifiedIdeograph.txt
EQUIVALENTS = {'⺁': '厂', '⺈': '刀', '⺊': '卜', '⺌': '小', '⺗': '心',
               '⺪': '\U00024D14', '⺮': '\U00025AD7', '⺶': '羊',
               '⺷': '\U0002634C', '⻊': '\U00027FB7'}


def build(check=False):
    main = json.loads((BASE / 'data.js').read_text(encoding='utf-8')[len('const HANZI = '):].strip().rstrip(';'))
    radicals = main['radicals']
    strokes = {record['c']: record['s'] for record in main['chars'] if record.get('s')}
    for line in (BASE / 'data/char_base.json').read_text(encoding='utf-8').splitlines():
        try:
            record = json.loads(line.strip().rstrip(','))
        except json.JSONDecodeError:
            continue
        if isinstance(record, dict) and type(record.get('strokes')) is int and record['strokes'] > 0:
            strokes.setdefault(record['char'], record['strokes'])
    with zipfile.ZipFile(BASE / 'data/Unihan.zip') as archive:
        for line in archive.read('Unihan_IRGSources.txt').decode().splitlines():
            if not line or line.startswith('#'):
                continue
            cp, field, value = line.split('\t', 2)
            if field == 'kTotalStrokes':
                strokes.setdefault(chr(int(cp[2:], 16)), int(value.split()[0]))
    result = {}
    for radical in radicals:
        count = strokes.get(radical) or strokes.get(EQUIVALENTS.get(radical))
        if not count:
            raise SystemExit('缺少现代部首笔画：' + radical)
        result[radical] = count
    text = '// Generated by scripts/build_radical_strokes.py; see assets/licenses/README.md.\n'
    text += 'const MODERN_RADICAL_STROKES = Object.freeze(' + json.dumps(result, ensure_ascii=False, separators=(',', ':')) + ');\n'
    target = BASE / 'assets/radical-strokes.js'
    if check:
        if not target.is_file() or target.read_text(encoding='utf-8') != text:
            raise SystemExit('现代部首笔画索引缺失或过期，请运行 python3 scripts/build_radical_strokes.py。')
    else:
        target.write_text(text, encoding='utf-8')
    print(f'现代部首笔画：{len(result)} 个，{min(result.values())}–{max(result.values())} 画，{len(text.encode())} 字节')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='只校验，不写文件')
    build(parser.parse_args().check)
